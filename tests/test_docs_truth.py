"""The docs must quote the numbers the shipped audits produce and must not keep claims the audit of 21.10.2026 found false."""
import json,unittest
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
ACCEPTANCE=(ROOT/'docs/ACCEPTANCE.md').read_text()
CURRENT=ACCEPTANCE.split('## Current state',1)[1].split('\n## ',1)[0] if '## Current state' in ACCEPTANCE else ''
MODEL_AUDIT=ROOT/'public/data/projection-model-audit.json'

class DocsTruth(unittest.TestCase):
    def test_current_state_section_exists_and_records_owner_decisions(self):
        self.assertTrue(CURRENT,'docs/ACCEPTANCE.md needs its «Current state» section')
        for text in ['EXACT_MINUTES','first holder','1st place','mean of ESPN']:
            self.assertIn(text,CURRENT)

    def test_in_season_figures_match_the_calibration_file(self):
        h=json.loads((ROOT/'data/inseason-calibration.json').read_text())['holdout']
        e,n=h['established'],h['newcomer']
        line=f"{e['currentMAE']:.2f} → {e['calibratedMAE']:.2f} FP for established players, {n['currentMAE']:.2f} → {n['calibratedMAE']:.2f} for newcomers"
        self.assertIn(line,CURRENT,'update the in-season bullet of «Current state» in docs/ACCEPTANCE.md')

    @unittest.skipUnless(MODEL_AUDIT.exists(),'public/data is generated by the build')
    def test_holdout_figures_match_the_projection_model_audit(self):
        h=json.loads(MODEL_AUDIT.read_text())['holdout'];t=h['transferValue']
        gain=lambda k:100*(t[k]['withReplacements']/t[k]['ownForecast']-1)
        expected=[f"{h['players']} players",f"{100*h['coverage80']:.1f}% inside the 80% range",
                  f"FP/game {h['perGameMAE']:.2f} vs {h['persistencePerGameMAE']:.2f}",
                  f"short-season Brier {h['shortSeasonBrier']:.3f} vs {h['shortSeasonBaseRateBrier']:.3f}",
                  f"slot MAE {t['slotMAE']['withReplacements']:.0f} vs {t['slotMAE']['ownForecast']:.0f}",
                  f"the 40 best slots by the new value produced {gain('top40SlotPoints'):.1f}% more",
                  f"the 80 best {gain('top80SlotPoints'):.1f}% more"]
        for text in expected:
            self.assertIn(text,CURRENT,'«Current state» in docs/ACCEPTANCE.md disagrees with projection-model-audit.json')

    def test_claims_found_false_are_gone_or_marked(self):
        readme=(ROOT/'README.md').read_text()
        for stale in ['multi-position matching','Official-price/cap checks are optional','untouched 2025/26','report in the app']:
            self.assertNotIn(stale,readme)
        for stale in ['Prices currently OFF','(485 players','Зак Онн has 135 lines','the same categories as Sports.ru\'s formula',
                      'The confidence percentage is the fraction of 100 stress scenarios','One unresolved Antetokounmpo record',
                      'Kawhi Leonard and Rob Dillingham lack source prices']:
            self.assertNotIn(stale,ACCEPTANCE)
        scoring=(ROOT/'docs/SCORING_AUDIT.md').read_text()
        self.assertNotIn('(Yahoo is a mirror only)',scoring);self.assertIn('external check',scoring)
        self.assertNotIn('Статус: сбор и аудит; тесты модели и публикация приостановлены пользователем.',(ROOT/'docs/DATA_FOUNDATION.md').read_text())

    def test_scoring_checks_are_not_called_independent(self):
        self.assertNotIn('Independent',(ROOT/'scripts/audit_scoring.py').read_text().split('\n',1)[0])
        self.assertNotIn('Independent all-player scoring audit',(ROOT/'scripts/verify-build.js').read_text())

if __name__=='__main__':unittest.main()
